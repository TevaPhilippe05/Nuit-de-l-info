    <section>
        <p>La <strong>Démarche NIRD</strong> est une initiative visant à transformer l'environnement numérique des établissements scolaires en le rendant plus éthique, écologique et accessible. Face aux défis tels que la fin de support de Windows 10 et l'urgence écologique, cette approche est essentielle pour garantir la <strong>souveraineté numérique</strong> et l'équité d'accès pour tous les élèves.</p>
    </section>
    <hr>
    <section>
        <h2>Les Trois Piliers de la Démarche NIRD</h2>
        <p>La philosophie de la démarche repose sur trois axes fondamentaux qui guident toutes les actions :</p>  
        <div class="pillars-nird">
            <article>
                <h3>1. Inclusion</h3>
                <ul>
                    <li>Assurer un <strong>accès équitable au numérique</strong> pour tous. Cela passe par la réduction de la fracture numérique et la garantie que chaque élève dispose d'outils adaptés à ses besoins.</li>
                </ul>
            </article>
            <article>
                <h3>2. Responsabilité</h3>
                <ul>
                    <li>Promouvoir un <strong>usage raisonné et réflexif</strong> des technologies. Ce pilier met l'accent sur l'utilisation de <strong>technologies souveraines</strong> et le <strong>respect strict des données personnelles</strong> (conformité RGPD).</li>
                </ul>
            </article>
            <article>
                <h3>3. Durabilité</h3>
                <ul>
                    <li>Lutter activement contre l'<strong>obsolescence programmée</strong>. Le choix de solutions pérennes, notamment le système d'exploitation <strong>Linux</strong>, permet la réutilisation de matériel ancien et la <strong>maîtrise des coûts</strong> à long terme.</li>
                </ul>
            </article>
        </div>
    </section>
    <hr>
    <section>
        <h2>Les Trois Jalons de la Mise en Œuvre</h2>
        <p>L'intégration de la démarche NIRD se fait progressivement, à travers trois étapes clés qui mobilisent l'ensemble de la communauté éducative et les partenaires territoriaux. </p>
        <div class="jalons-nird">
            <article>
                <h3>1. Mobilisation (Sensibilisation et Lancement)</h3>
                <ul>
                    <li><strong>Objectif :</strong> Sensibiliser l'établissement et initier une dynamique collective.</li>
                    <li><strong>Actions clés :</strong> Désignation d'un enseignant volontaire comme <strong>contact NIRD</strong>. Organisation d'un premier temps d'<strong>information</strong> auprès de l'équipe éducative. Mise en réseau du contact sur Tchap. <strong>Information et soutien</strong> de la direction et de la collectivité.</li>
                    <li><strong>Résultat attendu :</strong> Prise de conscience collective, constitution d'un premier relais interne, et soutien institutionnel.</li>
                </ul>
            </article>
            <article>
                <h3>2. Expérimentation (Test et Évaluation)</h3>
                <ul>
                    <li><strong>Objectif :</strong> Tester des solutions concrètes et évaluer leur pertinence pour l’établissement et les usagers.</li>
                    <li><strong>Actions clés :</strong> <strong>Installation et usage de postes de travail</strong> équipés de <strong>Linux</strong>. Création d'un <strong>club informatique</strong> ou utilisation de <strong>PrimTux</strong> pour le reconditionnement. Séances de <strong>formation</strong>. Début d'un <strong>suivi rigoureux</strong> par le coordinateur NIRD et la direction.</li>
                    <li><strong>Résultat attendu :</strong> Une première expérience documentée et analysée, éclairant la stratégie à long terme.</li>
                </ul>
            </article>
            <article>
                <h3>3. Intégration (Pérennisation et Structure)</h3>
                <ul>
                    <li><strong>Objectif :</strong> Inscrire durablement la démarche NIRD dans l’établissement et lui donner une portée structurelle.</li>
                    <li><strong>Actions clés :</strong> <strong>Intégration progressive</strong> des postes au parc informatique. Inscription de la démarche dans le <strong>projet d'établissement</strong>. Le coordinateur devient <strong>référent NIRD</strong> officiel, et la direction le <strong>pilote institutionnel</strong>. Mise en place d'une <strong>coopération structurée avec la collectivité</strong>.</li>
                    <li><strong>Résultat attendu :</strong> Intégration complète et institutionnellement soutenue, connectée à la collectivité et inscrite dans la durée.</li>
                </ul>
            </article>
        </div>
    </section>
    <hr>
    <section>
        <h2>Pourquoi le Choix de Linux : Le Système d'Exploitation Libre</h2>
        <p>Le passage à <strong>Linux</strong> (système d'exploitation libre) est un choix <strong>structurant et transformant</strong> qui soutient pleinement les trois dimensions de la démarche NIRD. Chaque machine sous Linux devient un outil pédagogique, éthique et écologique.</p>
        <div class="pillars-linux">
            <article>
                <h3>1. Un Choix Inclusif : Accessibilité Universelle</h3>
                <ul>
                    <li><strong>Accessibilité :</strong> Gratuit et sans licence, il permet d'équiper <strong>davantage d'élèves</strong>.</li>
                    <li><strong>Adaptation :</strong> Des distributions comme <strong>PrimTux</strong> (pour l'école primaire) offrent des interfaces et des ressources éducatives libres adaptées.</li>
                    <li><strong>Pédagogie active :</strong> Découverte du fonctionnement d'un <strong>système libre</strong> et développement de la <strong>culture critique du numérique</strong>.</li>
                </ul>
            </article>
            <article>
                <h3>2. Un Choix Responsable : Éthique et Souveraineté</h3>
                <ul>
                    <li><strong>Données Personnelles :</strong> Ne collecte pas d'informations commerciales, assurant un environnement <strong>protégé et conforme au RGPD</strong>.</li>
                    <li><strong>Maîtrise :</strong> L'établissement garde le <strong>contrôle de ses choix technologiques</strong>.</li>
                    <li><strong>Formation Citoyenne :</strong> Familiarisation avec les valeurs de <strong>partage et de coopération</strong>.</li>
                </ul>
            </article>
            <article>
                <h3>3. Un Choix Durable : Écologie et Économie</h3>
                <ul>
                    <li><strong>Optimisation :</strong> Donne une <strong>seconde vie aux ordinateurs de plus de dix ans</strong>, évitant des dépenses.</li>
                    <li><strong>Environnement :</strong> Contribue à la <strong>réduction des déchets électroniques</strong> et promeut la <strong>sobriété numérique</strong>.</li>
                    <li><strong>Pérennité :</strong> Cycles de support longs et communauté active pour une utilisation fiable sur le long terme.</li>
                </ul>
            </article>
        </div>
        <p>Différentes distributions sont envisagées :</p>
        <ul>
            <li><strong>PrimTux</strong> : Distribution adaptée pour l'école primaire (3-10 ans).</li>
            <li><strong>Linux NIRD</strong> : Distribution envisagée pour les collèges et lycées.</li>
        </ul>
    </section>
    <hr>
    <p>La démarche NIRD s'inscrit pleinement dans les objectifs de l'Éducation nationale de sensibiliser au développement durable et de soutenir les communs numériques.</p>
